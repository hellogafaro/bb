export function mascotPath(rows: MascotRows): string {
  let path = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x += 1;
        continue;
      }
      let run = 1;
      while (row[x + run] === "#") run += 1;
      path += `M${x} ${y}h${run}v1h-${run}z`;
      x += run;
    }
  });
  return path;
}

const SPRITES = new Map<AgentMascot, MascotSprite>(
  AGENT_MASCOTS.map((name) => [
    name,
    {
      name,
      restPath: mascotPath(REST[name]),
      talkPath: mascotPath(TALK[name]),
    },
  ]),
);

export function mascotSprite(name: AgentMascot): MascotSprite {
  const sprite = SPRITES.get(name);
  if (sprite === undefined) throw new Error(`Unknown mascot: ${name}`);
  return sprite;
}
